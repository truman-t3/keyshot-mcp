import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { format } from "prettier";
import { z } from "zod";
import { TOOL_CATALOG } from "../dist/tools/catalog.js";

const projectRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);
const outputPath = path.join(projectRoot, "docs", "TOOLS.md");
const checkOnly = process.argv.includes("--check");
const generated = await format(renderToolsDocument(), { parser: "markdown" });

if (checkOnly) {
  const current = fs.existsSync(outputPath)
    ? fs.readFileSync(outputPath, "utf8")
    : "";
  if (normalizeEol(current) !== normalizeEol(generated)) {
    throw new Error(
      "docs/TOOLS.md is out of date. Run `pnpm docs:tools` and commit the result.",
    );
  }
  console.log("docs/TOOLS.md matches the tool catalog.");
} else {
  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, generated, "utf8");
  console.log(
    `Generated ${path.relative(projectRoot, outputPath)} with ${TOOL_CATALOG.length} tools.`,
  );
}

function normalizeEol(value) {
  return value.replaceAll("\r\n", "\n");
}

function renderToolsDocument() {
  const groups = new Map();
  for (const tool of TOOL_CATALOG) {
    const entries = groups.get(tool.group) ?? [];
    entries.push(tool);
    groups.set(tool.group, entries);
  }

  const lines = [
    "# KeyShot MCP Tool Reference",
    "",
    "> Generated from `src/tools/catalog.ts`. Do not edit this file by hand.",
    "",
    `KeyShot MCP exposes ${TOOL_CATALOG.length} tools. All tools return JSON text and structured content using the common result schema.`,
    "",
  ];

  for (const [group, tools] of groups) {
    lines.push(`## ${group}`, "");
    for (const tool of tools) {
      lines.push(
        `### \`${tool.name}\``,
        "",
        `**${tool.title}**`,
        "",
        tool.description,
        "",
      );
      lines.push(
        `Safety: ${tool.annotations.readOnlyHint ? "read-only" : "writes output"}; ` +
          `${tool.annotations.destructiveHint ? "potentially destructive" : "non-destructive"}; ` +
          `${tool.annotations.openWorldHint ? "uses external services" : "local only"}.`,
        "",
      );
      const parameters = Object.entries(tool.inputSchema.shape);
      if (parameters.length === 0) {
        lines.push("Parameters: none.", "");
        continue;
      }
      lines.push(
        "| Parameter | Required | Type | Description |",
        "| --- | --- | --- | --- |",
      );
      for (const [name, schema] of parameters) {
        lines.push(
          `| \`${name}\` | ${schema.safeParse(undefined).success ? "No" : "Yes"} | ${schemaType(schema)} | ${escapeCell(z.toJSONSchema(schema, { io: "input" }).description ?? "")} |`,
        );
      }
      lines.push("");
    }
  }
  return `${lines.join("\n").trim()}\n`;
}

function schemaType(schema) {
  return jsonSchemaType(z.toJSONSchema(schema, { io: "input" }));
}

function jsonSchemaType(schema) {
  if (schema.enum)
    return schema.enum.map((value) => `\`${value}\``).join(" / ");
  if (schema.type === "array") {
    if (schema.prefixItems) return "tuple";
    return `${jsonSchemaType(schema.items ?? {})}[]`;
  }
  if (schema.type === "integer") return "number";
  return schema.type ?? "value";
}

function escapeCell(value) {
  return value.replaceAll("|", "\\|").replaceAll("\n", " ");
}
